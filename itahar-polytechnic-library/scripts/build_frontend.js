#!/usr/bin/env node
/**
 * build_frontend.js  –  Netlify pre-build script
 *
 * Reads VITE_API_BASE (or API_BASE) from the environment and writes
 *   public/config.js
 * which injects window.API_BASE into the browser at runtime.
 *
 * Usage (Netlify build command):
 *   node scripts/build_frontend.js
 *
 * When VITE_API_BASE is not set the script writes an empty string so the
 * browser falls back to same-origin (useful for local dev).
 */

const fs = require('fs');
const path = require('path');

const apiBase = (process.env.VITE_API_BASE || process.env.API_BASE || '').trim().replace(/\/$/, '');

const configContent = `// Auto-generated by scripts/build_frontend.js — DO NOT EDIT MANUALLY
// Set VITE_API_BASE in Netlify → Site configuration → Environment variables
window.API_BASE = "${apiBase}";
`;

const outputPath = path.join(__dirname, '..', 'public', 'config.js');
fs.writeFileSync(outputPath, configContent, 'utf8');

console.log(`[build_frontend] Wrote public/config.js  →  API_BASE="${apiBase || '(same-origin)'}"`);
